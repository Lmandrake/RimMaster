def _rownames():
    """Row labels from V1.md, so the board and the burn-down cannot disagree.

    Re-implemented from `derive_matrix.rownames()` rather than imported: rimflow is
    stdlib-only and must not take a dependency on a Utils script that reads the
    queues it is replacing.
    """
    out = {}
    try:
        with open(os.path.join(STATE, "V1.md"), encoding="utf-8") as fh:
            for ln in fh:
                m = re.match(r"\|\s*(\d+)\s*\|\s*([^|]+?)\s*\|", ln)
                if m:
                    out[m.group(1)] = "%s %s" % (m.group(1), m.group(2))
    except OSError:
        pass
    return out


def _rowkey(it):
    return (str(it.row).strip() if it.row not in (None, "") else "unassigned")


def _velocity(close_days, remaining):
    """Closes per day, straight off the `close` events. Same shape as derive_matrix.

    ⚠️ `eta_days` is a trend line, not a date: it assumes today's rate and a fixed
    scope, and v1's scope has already moved once.
    """
    if not close_days:
        return {"days": [], "per_day": 0.0, "closed": 0,
                "remaining": remaining, "eta_days": None}
    span = sorted(close_days)
    total = sum(close_days.values())
    try:
        import datetime as _dt
        elapsed = max(1, (_dt.date.fromisoformat(span[-1])
                          - _dt.date.fromisoformat(span[0])).days + 1)
    except Exception:
        elapsed = max(1, len(span))
    rate = total / elapsed
    return {"days": [{"d": d, "n": close_days[d]} for d in span],
            "per_day": round(rate, 2), "closed": total, "remaining": remaining,
            "eta_days": int(round(remaining / rate)) if rate and remaining else None}


def board(world, events, target="v1", ctx=None):
    """-> dict. Everything the status board needs, from the ledger alone."""
    closed_at, close_days = _closing_events(events)
    names = _rownames()

    # --- rows, in status_matrix.json's shape -------------------------------
    grid = {}
    for it in world.items.values():
        if it.owner not in COLS:
            continue
        grid.setdefault(_rowkey(it), {c: [] for c in COLS})[it.owner].append(it)
    order = sorted(names, key=int) + [k for k in sorted(grid) if k not in names]
    rows = []
    for key in order:
        cells = {}
        for col in COLS:
            its = [i for i in grid.get(key, {}).get(col, [])
                   if i.state not in ("dropped", "superseded")]
            # `closed` vs `done`: derive_matrix split these because its numerator came
            # from git trailers and its denominator from the queue files. Here every
            # close carries a sha in the ledger, so all of them are `closed` and
            # `done` is structurally zero. The renderer sums both segments, so the
            # bar draws identically.
            done = sum(1 for i in its if i.state == "done")
            st = ("blocked" if any(i.blocked for i in its)
                  else "working" if any(i.state == "doing" for i in its)
                  else "offline" if not its
                  else "idle" if done < len(its) else "idle")
            cells[col] = {
                "done": done, "total": len(its), "state": st,
                "mix": {"closed": done, "done": 0,
                        "doing": sum(1 for i in its if i.state == "doing"),
                        "blocked": sum(1 for i in its if i.blocked),
                        "ready": sum(1 for i in its
                                     if i.state in ("proposed", "ready")
                                     and not i.blocked)}}
        rows.append({"name": names.get(key, key), "cells": cells})

    # --- blockers ----------------------------------------------------------
    classes, on_human = {}, 0
    blocked_list = []
    for it in sorted(world.items.values(), key=lambda i: i.id):
        if not (it.blocked and it.open):
            continue
        reason = it.blocked_reason or "unexplained"
        classes[reason] = classes.get(reason, 0) + 1
        if it.needs == "owner" or re.search(r"human|owner", reason, re.I):
            on_human += 1
        blocked_list.append({"id": it.id, "owner": it.owner, "state": it.state,
                             "reason": reason, "on": it.blocked_on,
                             "needs": it.needs, "row": it.row})

    # --- per seat ----------------------------------------------------------
    seats = {}
    for seat in VIEW_SEATS:
        mine = [i for i in world.items.values() if i.owner == seat]
        counts = {s: sum(1 for i in mine if i.state == s) for s in model.STATES}
        offered = priority.rank(world, seat, target, ctx)
        said = world.seats.get(seat) or {}
        doing = sorted(i.id for i in mine if i.state == "doing")
        seats[seat] = {
            "counts": counts,
            "open": sum(1 for i in mine if i.open),
            "blocked": sum(1 for i in mine if i.blocked and i.open),
            "offered": len(offered),
            "next": offered[0].id if offered else None,
            # 🔑 Two DIFFERENT readings of "what is this seat doing", kept apart on
            # purpose. `doing` is what the ledger's item states say. `says` is what
            # the seat last announced about itself. When they disagree, that IS the
            # finding — a seat announcing busy with nothing started is the failure
            # mode the old board could not see.
            "doing": doing,
            "says": {"state": said.get("state"), "reason": said.get("reason"),
                     "item": said.get("item")},
        }

    tot = sum(c["total"] for r in rows for c in r["cells"].values())
    don = sum(c["done"] for r in rows for c in r["cells"].values())
    return {
        "schema": "rimflow-board/1",
        "as_of": as_of(events),
        "events": len(events),
        "items": len(world.items),
        "game": world.game,
        "bridge_holder": world.bridge_holder,
        "target": target,
        "rows": rows,
        "blockers": {"on_human": on_human,
                     "classes": [{"label": k, "count": v} for k, v in
                                 sorted(classes.items(), key=lambda kv: (-kv[1], kv[0]))]},
        "velocity": _velocity(close_days, tot - don),
        "seats": seats,
        "blocked": blocked_list,
        "findings": world.findings,
        # Refusals already IN the append-only file. Surfaced, never swallowed: an
        # event that replay rejected is a fact about the ledger, not a crash.
        "errors": [{"index": i, "event": v, "message": m} for i, v, m in world.errors],
    }


