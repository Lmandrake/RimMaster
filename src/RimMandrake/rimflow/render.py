#!/usr/bin/env python3
"""rimflow/render.py — every derived view, rebuilt from `events.jsonl` alone.

WHAT THIS PRODUCES, AND WHY EACH ONE IS DERIVED
===============================================
Two artifacts, and neither is ever hand-edited:

    infrastructure/state/queue/<SEAT>.md      a GENERATED VIEW of the one ledger
    infrastructure/state/derived/board.json   everything the status board needs

The queue view exists so that a human reading a file and a seat running
`rimflow next` **cannot disagree**. The items are emitted in `priority.rank()`
order — the same function `next` calls, not a re-implementation of it — so the
top of the file IS the next item, by construction rather than by discipline.

⛔ THE VIEW CARRIES ONE LINE PER ITEM, NEVER THE PROSE.
The prose lives in `items/<ID>.md` and copying it here would recreate exactly the
drift the ledger was built to end: 827 KB of markdown in which the same item sat
in two queues with two different states. A summary line is a POINTER. If it is
wrong, nothing breaks, because nothing reads it but a human deciding whether to
open the item.

🔴 `render` DOES NOT WRITE `queue/*.md` BY DEFAULT, AND THAT IS THE POINT.
Those six files are the hand-written source of 142 items and ~827 KB of prose, and
until a human has checked the importer against them, a generator pointed at them is
a shredder. So the default target is `derived/queue_preview/<SEAT>.md` plus a diff
summary, and `--overwrite-queues` REFUSES unless the ledger holds at least as many
items as the queues do — printing both counts, because "it refused" without the
numbers tells you nothing about what to fix.

⭐ THE OUTPUT IS A PURE FUNCTION OF THE LEDGER — NO WALL CLOCK ANYWHERE.
`as_of` is the timestamp of the last EVENT, not the moment of rendering. That is
not cosmetic: it is what makes `reindex --verify` a real test. If a rendered
artifact carried `generated_at: now`, every verification would differ for a reason
that means nothing, and a byte-comparison that always fails teaches people to
ignore it. With the clock removed, a difference means exactly one of two things —
a bug in this file, or somebody hand-edited a generated artifact — and both are
things you want to be told about.

Stdlib only.

    python3 src/RimMandrake/rimflow/render.py                 render + diff summary
    python3 src/RimMandrake/rimflow/render.py --overwrite-queues
    python3 src/RimMandrake/rimflow/render.py reindex
    python3 src/RimMandrake/rimflow/render.py reindex --verify
    python3 src/RimMandrake/rimflow/render.py bench --events 2000
"""
import json
import os
import re
import shutil
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
if os.path.dirname(HERE) not in sys.path:
    sys.path.insert(0, os.path.dirname(HERE))

from rimflow import model, priority                                  # noqa: E402

STATE = model.STATE
QUEUE = os.path.join(STATE, "queue")
DERIVED = os.path.join(STATE, "derived")
PREVIEW = os.path.join(DERIVED, "queue_preview")
BOARD = os.path.join(DERIVED, "board.json")

# The seats that get a rendered view, in board order. OWNER's queue file has always
# been called HUMAN.md; the view keeps that name so a diff against the real file is
# a direct comparison rather than a rename nobody asked for.
VIEW_SEATS = ("DECIDE", "BUILD", "CHECK", "REP", "OWNER")
FILENAME = {"OWNER": "HUMAN"}

# ⚠️ `rows` keeps THREE columns because `status_server.py` renders exactly three and
# a fourth would push a column off the grid. REP and OWNER are not dropped — they are
# reported in `seats`, which is new. See the header note in board().
COLS = ("DECIDE", "BUILD", "CHECK")

MARKER = "<!-- generated by rimflow render — derived, do not edit -->"
REGEN = "python3 src/RimMandrake/rimflow/render.py"

CLOSING = ("close", "drop", "supersede")
SUMMARY_WIDTH = 110


# ---------------------------------------------------------------------------
# READING THE LEDGER
# ---------------------------------------------------------------------------
def build(events_path=None):
    """-> (world, events). One read, one replay; everything below is pure."""
    path = events_path or model.EVENTS
    events = model.read(path)
    return model.replay(events), events


def _closing_events(events):
    """-> (closed_at, close_days).

    `closed_at` is per item and covers close/drop/supersede, because "what left the
    queue recently" is the question the view answers. `close_days` counts `close`
    ONLY — a dropped item is scope leaving, not work landing, and mixing the two is
    how a velocity line starts flattering itself.
    """
    closed_at, close_days = {}, {}
    for ev in events:
        verb = ev.get("event")
        if verb not in CLOSING:
            continue
        iid, ts = ev.get("id"), ev.get("ts") or ""
        if iid:
            closed_at[iid] = ts
        if verb == "close" and ts:
            day = ts[:10]
            close_days[day] = close_days.get(day, 0) + 1
    return closed_at, close_days


def as_of(events):
    """The ledger's own clock. `None` on an empty ledger, which is honest."""
    for ev in reversed(events):
        if ev.get("ts"):
            return ev["ts"]
    return None


# ---------------------------------------------------------------------------
# THE ONE-LINE SUMMARY
# ---------------------------------------------------------------------------
_SPEC_RE = re.compile(r"^##\s+spec\s*$(.*?)(?=^##\s|\Z)", re.M | re.S | re.I)
_STRIP = re.compile(r"[`*_>#\[\]]")


# 🔴 ONE `listdir`, NOT ONE `open` PER ITEM. MEASURED, NOT ASSUMED.
# On this repo's 9p/DrvFs mount a failed `open()` costs ~0.8 ms — 500 of them is
# 404 ms, against 0.8 ms total on tmpfs. So an item with no prose file must never
# reach the filesystem: the directory is listed ONCE per render and absence is
# answered from that set. Rendering the whole ledger is supposed to cost less than
# one of those opens.
_INDEX = {"dir": None, "names": frozenset(), "cache": {}}


def item_index(items_dir=None, refresh=False):
    d = items_dir or model.ITEMS
    if refresh or _INDEX["dir"] != d:
        try:
            names = frozenset(os.listdir(d))
        except OSError:
            names = frozenset()
        _INDEX.update(dir=d, names=names, cache={})
    return _INDEX


def summary(iid, items_dir=None):
    """First sentence of `## spec`, flattened to ONE line.

    ⛔ Not the prose. This is a pointer at `items/<ID>.md`, deliberately lossy: a
    reader decides from it whether to open the item, and nothing else reads it at
    all. An item with no file says so, because "missing" is a fact worth seeing in
    the queue rather than a blank.
    """
    idx = item_index(items_dir)
    if iid in idx["cache"]:
        return idx["cache"][iid]
    name = "%s.md" % iid
    if name not in idx["names"]:
        return "(no items/%s.md yet — cannot enter `ready` without spec/verify/criteria)" % iid
    try:
        with open(os.path.join(idx["dir"], name), encoding="utf-8") as fh:
            text = fh.read()
    except OSError:
        return "(no items/%s.md yet — cannot enter `ready` without spec/verify/criteria)" % iid
    m = _SPEC_RE.search(text)
    body = m.group(1) if m else text
    for raw in body.splitlines():
        line = _STRIP.sub("", raw).strip()
        if line:
            line = " ".join(line.split())
            if len(line) > SUMMARY_WIDTH:
                line = line[:SUMMARY_WIDTH - 1].rstrip() + "…"
            idx["cache"][iid] = line
            return line
    return "(items/%s.md has no ## spec text)" % iid


