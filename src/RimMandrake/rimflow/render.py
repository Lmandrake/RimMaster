#!/usr/bin/env python3
"""rimflow/render.py — every derived view, rebuilt from `events.jsonl` alone.

WHAT THIS PRODUCES, AND WHY EACH ONE IS DERIVED
===============================================
One artifact, never hand-edited:

    infrastructure/state/queue/<SEAT>.md      a GENERATED VIEW of the one ledger

⭐ 2026-08-27: `board.json` and the status board it fed are GONE. The owner retired
the web page — git is the provenance — so this module renders queue views and
nothing else.

The queue view exists so that a human reading a file and a seat running
`rimflow next` **cannot disagree**. The items are emitted in `priority.rank()`
order — the same function `next` calls, not a re-implementation of it — so the
top of the file IS the next item, by construction rather than by discipline.

⛔ THE VIEW CARRIES ONE LINE PER ITEM, NEVER THE PROSE.
The prose lives in `items/<ID>.md` and copying it here would recreate exactly the
drift the ledger was built to end: 827 KB of markdown in which the same item sat
in two queues with two different states. A summary line is a POINTER. If it is
wrong, nothing breaks, because nothing reads it but a human deciding whether to
open the item.

🔴 `render` DOES NOT WRITE `queue/*.md` BY DEFAULT, AND THAT IS THE POINT.
Those six files are the hand-written source of 142 items and ~827 KB of prose, and
until a human has checked the importer against them, a generator pointed at them is
a shredder. So the default target is `derived/queue_preview/<SEAT>.md` plus a diff
summary, and `--overwrite-queues` REFUSES unless the ledger holds at least as many
items as the queues do — printing both counts, because "it refused" without the
numbers tells you nothing about what to fix.

⭐ THE OUTPUT IS A PURE FUNCTION OF THE LEDGER — NO WALL CLOCK ANYWHERE.
`as_of` is the timestamp of the last EVENT, not the moment of rendering. That is
not cosmetic: it is what makes `reindex --verify` a real test. If a rendered
artifact carried `generated_at: now`, every verification would differ for a reason
that means nothing, and a byte-comparison that always fails teaches people to
ignore it. With the clock removed, a difference means exactly one of two things —
a bug in this file, or somebody hand-edited a generated artifact — and both are
things you want to be told about.

Stdlib only.

    python3 src/RimMandrake/rimflow/render.py                 render + diff summary
    python3 src/RimMandrake/rimflow/render.py --overwrite-queues
    python3 src/RimMandrake/rimflow/render.py reindex
    python3 src/RimMandrake/rimflow/render.py reindex --verify
    python3 src/RimMandrake/rimflow/render.py bench --events 2000
"""
