def _norm(v):
    if v is None:
        return None
    try:
        return round(float(v), 9)
    except (TypeError, ValueError):
        return v


def _collect_node_signatures(fg, collect_scalar_fields):
    """(scalar multiset, floatrange multiset, variable multiset) for one FileGraph."""
    scalars = Counter()
    franges = Counter()
    variables = Counter()
    for _nid, ninfo in fg.nodes.items():
        ntype = ninfo["type"]
        fields = defaultdict(list)
        frs = defaultdict(list)
        vars_ = defaultdict(list)
        collect_scalar_fields(ninfo["el"], fields, frs, vars_)
        for (tag, name), values in fields.items():
            if name in ("RandSeed", "TimeCreated"):
                continue
            for v in values:
                scalars[(ntype, tag, name, _norm(v))] += 1
        for name, pairs in frs.items():
            for mn, mx in pairs:
                franges[(ntype, name, _norm(mn), _norm(mx))] += 1
        for name, refids in vars_.items():
            for refid in refids:
                vals = _read_objects(fg.root).get(refid, {}).get("values", [])
                variables[(ntype, name, tuple(_norm(v) for v in vals))] += 1
    return scalars, franges, variables


def _connection_signature(fg):
    sig = Counter()
    for a, b, bad in fg.resolved_edges():
        if bad:
            continue
        pn, cn = fg.port_owner[a], fg.port_owner[b]
        key = (
            f'{fg.nodes[pn]["type"]}.{fg.port_name[a]}',
            f'{fg.nodes[cn]["type"]}.{fg.port_name[b]}',
        )
        sig[key] += 1
    return sig


def run_selftest():
    census = _load_gl_schema_census()

    g = Graph()
    build_desertplateau(g)
    tmp_path = os.path.join(tempfile.gettempdir(), "gl_emit_selftest_desertplateau.xml")
    g.write(tmp_path)

    orig = census.FileGraph(SOURCE_DESERTPLATEAU)
    emitted = census.FileGraph(tmp_path)

    checks = []

    orig_types = Counter(n["type"] for n in orig.nodes.values())
    emit_types = Counter(n["type"] for n in emitted.nodes.values())
    checks.append((
        "node-type multiset",
        orig_types == emit_types,
        f"{sum(orig_types.values())} vs {sum(emit_types.values())} nodes, "
        f"{len(orig_types)} vs {len(emit_types)} distinct types",
    ))

    o_scal, o_fr, o_var = _collect_node_signatures(orig, census.collect_scalar_fields)
    e_scal, e_fr, e_var = _collect_node_signatures(emitted, census.collect_scalar_fields)
    fields_ok = (o_scal == e_scal) and (o_fr == e_fr) and (o_var == e_var)
    checks.append((
        "field values (scalar+FloatRange+Variable, excl. RandSeed/TimeCreated/pos/ID)",
        fields_ok,
        f"scalar_eq={o_scal == e_scal} ({len(o_scal)} vs {len(e_scal)} distinct) "
        f"floatrange_eq={o_fr == e_fr} variable_eq={o_var == e_var}",
    ))

    o_ports, e_ports = len(orig.port_owner), len(emitted.port_owner)
    checks.append(("port count", o_ports == e_ports, f"{o_ports} vs {e_ports}"))

    o_conn = _connection_signature(orig)
    e_conn = _connection_signature(emitted)
    o_total, e_total = sum(o_conn.values()), sum(e_conn.values())
    checks.append((
        "connection set (srcType.port -> dstType.port multiset)",
        o_conn == e_conn,
        f"{o_total} vs {e_total} resolved edges (orig has 35 total incl. anomalies), equal={o_conn == e_conn}",
    ))

    try:
        ET.parse(tmp_path)
        reparse_ok = True
        reparse_detail = tmp_path
    except ET.ParseError as e:
        reparse_ok = False
        reparse_detail = str(e)
    checks.append(("emitted file re-parses with xml.etree", reparse_ok, reparse_detail))

    passed = sum(1 for _, ok, _ in checks if ok)
    total = len(checks)
    for label, ok, detail in checks:
        print(f"  [{'PASS' if ok else 'FAIL'}] {label}: {detail}")
    print(f"SELFTEST {'PASS' if passed == total else 'FAIL'} {passed}/{total}")
    return passed == total


# ==================================== CLI ====================================

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--selftest", action="store_true", help="rebuild DesertPlateau via the builder and census-compare it to the source")
    ap.add_argument("--variant", action="store_true", help="emit a DesertPlateau variant with a parametrized Perlin Frequency")
    ap.add_argument("--frequency", type=float, default=0.025, help="Frequency for the primary Perlin node (source Node ID=5)")
    ap.add_argument("--id", dest="landform_id", default=None, help="new landformManifest Id / DisplayName")
    ap.add_argument("--out", default=None, help="output path for --variant")
    args = ap.parse_args()

    if args.selftest:
        ok = run_selftest()
        sys.exit(0 if ok else 1)

    if args.variant:
        if not args.landform_id or not args.out:
            print("ERROR: --variant requires --id and --out", file=sys.stderr)
            sys.exit(2)
        g = Graph()
        build_desertplateau(
            g,
            frequency=args.frequency,
            manifest_overrides={
                "id": args.landform_id,
                "display_name": args.landform_id,
                "is_custom": True,
            },
            tile_req_overrides={
                "commonness": 1.0,
                "hilliness": (0.0, 6.0),
                "rainfall": (0.0, 10000.0),
                "avg_temperature": (-100.0, 100.0),
            },
        )
        path = g.write(args.out)
        print(f"Wrote {path}")
        sys.exit(0)

    ap.print_help()
    sys.exit(1)


if __name__ == "__main__":
    main()
