XSI_NIL_ATTR = "{http://www.w3.org/2001/XMLSchema-instance}nil"


def _load_gl_schema_census():
    """Import gl_schema_census.py's parser (FileGraph, collect_scalar_fields)
    without executing its module-level main() (guarded by __main__)."""
    spec = importlib.util.spec_from_file_location("gl_schema_census", GL_SCHEMA_CENSUS_PATH)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _esc(s):
    return (
        str(s)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def _fmt_scalar(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return value
    if value is None:
        return ""
    if isinstance(value, float):
        if value == int(value):
            return str(int(value))
        return repr(value)
    return str(value)


