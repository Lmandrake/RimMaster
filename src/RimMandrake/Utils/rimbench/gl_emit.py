#!/usr/bin/env python3
"""
gl_emit.py

A small typed builder that WRITES Geological Landforms landform-recipe XML
(NodeCanvas / GraphEditor.Landform) from Python, byte-shape compatible with
the files shipped in the Landforms-v1 workshop item.

Design: rather than hand-writing per-node-type XML templates, this module
LEARNS them by parsing the one ground-truth file it must reproduce
(LandformDesertPlateau.xml) once, at first use: which XML tag each scalar
field uses (string/int/long/double/float/boolean/Topology/...), which fields
are FloatRange or Variable/Object indirections, and the extra sub-element
block a dynamic Port carries. The VALUES written to any given file come from
whoever calls the builder; the per-type SHAPE comes from that parse.

stdlib only.

Builder API:
    g = Graph()
    node = g.node(type_, name, pos=None, **fields)
    port = g.port(node, name, direction, dynamic=False, **overrides)
    g.connect(port_a, port_b)
    node = g.manifest(id_, display_name, is_custom=True, ...)
    node = g.tile_req(**ranges)
    g.write(path)

--selftest   Rebuild LandformDesertPlateau.xml entirely via builder calls
             (the calls are generated by parsing the source once; the
             emitted bytes come from the builder, not a copy), then compare
             against the original using gl_schema_census's own parser
             (imported, not duplicated). Prints `SELFTEST PASS N/N`.

--variant --frequency F --id ID --out PATH
             DesertPlateau via the builder with the primary Perlin's
             (source Node ID=5) Frequency replaced by F, manifest Id/
             DisplayName set to ID, IsCustom true, Commonness 1, hilliness
             0-6, rainfall 0-10000, temperature -100..100.
"""
